#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""我的任务.py —— 你写飞行任务代码的地方。

【这个文件是干什么的】
这是一个最小的示例：控制一架飞机起飞 -> 飞到一个点 -> 降落。
你不需要新建文件、不需要写任何docker/ROS2相关的东西，直接改这个文件里的
几行代码，然后运行同一个文件夹里的"运行仿真.sh"（Linux/macOS）或者
"运行仿真.bat"（Windows），就能看到飞机按你写的逻辑飞起来。

【你应该怎么改】
最简单的改法：改下面 sdk.goto(...) 里的三个数字，让飞机飞到你想要的位置，
重新运行脚本，观察飞机的动作。等你熟悉了这几个方法之后，可以在这个文件里
加更多逻辑（比如多飞几个点、加检测、双机通信等），可以参考的方法清单见
下面"能用的方法有哪些"这一节。

【坐标系提醒】
下面 goto() 用的 x/y/z 是"你自己这架飞机"的局部坐标系（不是世界坐标、
也不是GPS经纬度），大致可以理解成"以这架飞机起飞点为原点，往前/往左/
往上的米数"。第一次运行建议先用一个不太远的小坐标（比如(2, 0, 1.5)），
确认飞机真的照你的指令飞了之后，再尝试更远的点。

【能用的方法有哪些】（这些都是contest_sdk真实提供的方法，不是随便写的）
    sdk.takeoff()                                起飞，等到确认已经离地才返回
    sdk.goto(x, y, z)                            飞到一个点，等到确认到达才返回
    sdk.land()                                    降落，等到确认落地才返回
    sdk.cancel_goto()                             中途打断正在飞的goto()
    sdk.wait_for_detection(class_id, timeout)     等待摄像头识别到某个目标
    sdk.do_action(name)                           触发一个动作（比如抓取/投放）
    sdk.send_to_teammate(event, **kwargs)         给队友那架飞机发一个消息
    sdk.on_teammate_event(event_name, callback)   注册"收到队友消息时"的处理函数
    sdk.start_formation_follow(follow_distance_m) 开启编队跟随（跟着队友飞）
    sdk.stop_formation_follow()                   关闭编队跟随
    sdk.set_mission_state(state) / sdk.get_mission_state()   记录/查询任务进度
    sdk.world_to_local(x, y, z)                   把世界坐标换算成自己能用的局部坐标
更完整的方法说明，可以让助教/队友帮你看contest_sdk的源码注释，或者问一下
带你的技术负责人——这里只列最常用的几个，帮你先跑起来。

【关于下面的DroneSDK(...)三个参数】
本示例先写死了几个默认值（NX01/recon/NX02），方便你拿到手第一眼就能跑，
不需要一开始就学命令行参数。等你需要跟队友配合写更完整的任务的时候，
再问一下技术负责人怎么改这几个值（正式比赛用的任务程序会支持在启动的
时候传参数指定，不需要改代码），这里先专注在"能不能让飞机动起来"这一步。
"""

from contest_sdk import DroneSDK


def main():
    # ------------------------------------------------------------------
    # 第一步：创建SDK对象——告诉SDK"我是哪架飞机、这次我扮演什么角色、
    # 我的队友是哪架飞机"。
    #   namespace          自己这架飞机的编号，比如 'NX01' / 'NX02'
    #   role                自己这次扮演的角色，名字随便取，你自己代码里用
    #   teammate_namespace  队友那架飞机的编号
    # 先用下面这组默认值就能跑起来，之后需要双机配合再调整。
    # ------------------------------------------------------------------
    sdk = DroneSDK(namespace='NX01', role='recon', teammate_namespace='NX02')

    try:
        # --------------------------------------------------------------
        # 第二步：起飞。这一行会一直等到飞机确认已经离地才往下走，
        # 中途会在终端里看到"起飞中…当前高度…"这样的进度提示。
        # --------------------------------------------------------------
        sdk.takeoff()

        # --------------------------------------------------------------
        # 第三步：飞到一个点。
        # 把下面的 2, 0, 1.5 改成你想让飞机去的地方（局部坐标，见文件顶部
        # 的坐标系提醒）——x往前多少米，y往左多少米，z飞多高（米）。
        # --------------------------------------------------------------
        sdk.goto(2, 0, 1.5)

        # --------------------------------------------------------------
        # 第四步：降落。同样会一直等到确认落地才往下走。
        # --------------------------------------------------------------
        sdk.land()

        print('任务完成！飞机已经安全落地。')

    finally:
        # 不管任务是正常结束还是中途出错，都记得调用一次shutdown()做
        # 干净收尾（这是SDK自己要求的收尾动作，跟你的飞行逻辑无关，
        # 照抄这一行就行，不需要每次都记得为什么要写它）。
        sdk.shutdown()


if __name__ == '__main__':
    main()
